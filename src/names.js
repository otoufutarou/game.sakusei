function usedNameSet(usedNames) {
  if (usedNames instanceof Set) return usedNames;
  return new Set(usedNames ?? []);
}

export function generatePersonName(random, gender, { usedNames = [], surname = null, culture = null } = {}) {
  const cultureRoll = random();
  const givenRoll = random();
  const selectedCulture = culture ?? NAME_CULTURES[Math.floor(cultureRoll * NAME_CULTURES.length)];
  const allGivenNames = gender === "女性" ? selectedCulture.female : selectedCulture.male;
  const regionalGivenNames = gender === "女性" ? selectedCulture.regionalFemale : selectedCulture.regionalMale;
  const useRegionalPool = givenRoll < 0.7;
  const givenNames = useRegionalPool ? regionalGivenNames : allGivenNames;
  const occupied = usedNameSet(usedNames);
  const normalizedGivenRoll = useRegionalPool ? givenRoll / 0.7 : (givenRoll - 0.7) / 0.3;
  const startGiven = Math.floor(normalizedGivenRoll * givenNames.length);
  const startSurname = Math.floor(((cultureRoll + givenRoll) % 1) * selectedCulture.surnames.length);

  for (let givenOffset = 0; givenOffset < givenNames.length; givenOffset += 1) {
    const givenName = givenNames[(startGiven + givenOffset) % givenNames.length];
    const surnameCount = surname ? 1 : selectedCulture.surnames.length;
    for (let surnameOffset = 0; surnameOffset < surnameCount; surnameOffset += 1) {
      const lastName = surname ?? selectedCulture.surnames[(startSurname + surnameOffset) % selectedCulture.surnames.length];
      const name = `${givenName}・${lastName}`;
      if (!occupied.has(name) && !FAMOUS_FULL_NAMES.has(name)) {
        return { name, givenName, surname: lastName, culture: selectedCulture.id };
      }
    }
  }

  let suffix = 2;
  let givenName = givenNames[startGiven];
  let name = `${givenName}・${surname ?? selectedCulture.surnames[startSurname]}`;
  while (occupied.has(name) || FAMOUS_FULL_NAMES.has(name)) {
    givenName = `${givenNames[(startGiven + suffix - 2) % givenNames.length]}${suffix}`;
    name = `${givenName}・${surname ?? selectedCulture.surnames[(startSurname + suffix - 2) % selectedCulture.surnames.length]}`;
    suffix += 1;
  }
  return { name, givenName, surname: name.split("・").at(-1), culture: selectedCulture.id };
}
